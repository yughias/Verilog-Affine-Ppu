// files.h - save, load and export of the scenario
#pragma once
#include "state.h"

static const char MAGIC[8] = {'P', 'P', 'U', 'S', 'C', 'N', '0', '1'};

// The file layout, shared by save and load: io(pointer, bytes) writes or reads one block
template <class IO>
static void transfer(Scenario& s, IO io) {
    for (int L = 0; L < 2; ++L) { io(s.map[L], sizeof s.map[L]); io(s.attr[L], sizeof s.attr[L]); }
    io(s.tile, sizeof s.tile);
    io(s.spr_tile, sizeof s.spr_tile);
    io(s.col, sizeof s.col);
    for (Sprite& p : s.spr) {
        int32_t v[5] = {p.x, p.y, p.tile, p.pal, p.on | (p.fx << 1) | (p.fy << 2) | (p.lo << 3)};
        io(v, sizeof v);
        p.x = v[0]; p.y = v[1]; p.tile = v[2] & 63; p.pal = v[3] & 15;
        p.on = v[4] & 1; p.fx = (v[4] >> 1) & 1; p.fy = (v[4] >> 2) & 1; p.lo = (v[4] >> 3) & 1;
        clamp_sprite(p);
    }
    for (Camera& c : s.cam) {
        double v[4] = {c.cx, c.cy, c.ang, c.zoom};
        io(v, sizeof v);
        c = Camera{};
        if (std::isfinite(v[0]) && std::isfinite(v[1]) && std::isfinite(v[2]) && std::isfinite(v[3])) {
            c.cx = wrapm(v[0]); c.cy = wrapm(v[1]); c.ang = v[2]; c.zoom = clampv(v[3], 0.125, 8.0);
        }
    }
    uint8_t lk = s.linked;
    io(&lk, 1);
    s.linked = lk != 0;
}

static bool save_file(const std::string& path) {
    FILE* f = fopen(path.c_str(), "wb");
    if (!f) return false;
    bool ok = fwrite(MAGIC, 1, 8, f) == 8;
    transfer(scene, [&](const void* p, size_t n) { ok = ok && fwrite(p, 1, n, f) == n; });
    return (fclose(f) == 0) && ok;
}
static bool load_file(const std::string& path, Scenario& out) {
    FILE* f = fopen(path.c_str(), "rb");
    if (!f) return false;
    char magic[8];
    bool ok = fread(magic, 1, 8, f) == 8 && memcmp(magic, MAGIC, 8) == 0;
    Scenario s{};
    transfer(s, [&](void* p, size_t n) { ok = ok && fread(p, 1, n, f) == n; });
    fclose(f);
    if (ok) out = s;
    return ok;
}

template <class T>
static void write_array(FILE* f, const char* name, const T* d, int n) {
    const int per_line = sizeof(T) == 1 ? 16 : 6;
    fprintf(f, "static const %s %s[%d] = {", sizeof(T) == 1 ? "uint8_t" : "uint32_t", name, n);
    for (int i = 0; i < n; ++i) fprintf(f, "%s0x%0*X,", i % per_line ? " " : "\n    ", (int)sizeof(T) * 2, (unsigned)d[i]);
    fprintf(f, "\n};\n\n");
}
static bool export_header(const std::string& path) {
    FILE* f = fopen(path.c_str(), "w");
    if (!f) return false;
    fprintf(f, "// Generated by the PPU scenario editor (editor.cpp) from %s\n"
               "// Copy each array into the matching Verilator memory right after reset (see simulate() in\n"
               "// editor/scenario.h). OAM words are already encoded; the register arrays are\n"
               "// {scroll_x, scroll_y, m00, m01, m10, m11} in 16.16.\n"
               "#pragma once\n#include <cstdint>\n\n", file_path.c_str());
    write_array(f, "SCN_BG_MAP", scene.map[L_BG], MAP_CELLS);
    write_array(f, "SCN_BG_ATTR", scene.attr[L_BG], MAP_CELLS);
    write_array(f, "SCN_FG_MAP", scene.map[L_FG], MAP_CELLS);
    write_array(f, "SCN_FG_ATTR", scene.attr[L_FG], MAP_CELLS);
    write_array(f, "SCN_BG_TILES", scene.tile[L_BG], LAYER_TILES * TILE_BYTES);
    write_array(f, "SCN_FG_TILES", scene.tile[L_FG], LAYER_TILES * TILE_BYTES);
    write_array(f, "SCN_SPR_TILES", scene.spr_tile, SPR_TILES * TILE_BYTES);
    write_array(f, "SCN_BG_COL", scene.col[L_BG], 256);
    write_array(f, "SCN_FG_COL", scene.col[L_FG], 256);
    write_array(f, "SCN_SPR_COL", scene.col[L_SPR], 256);
    uint32_t oam[NUM_OAM];
    for (int i = 0; i < NUM_OAM; ++i) oam[i] = sprite_oam(scene.spr[i]);
    write_array(f, "SCN_OAM", oam, NUM_OAM);
    for (int L = 0; L < 2; ++L) {
        Regs g = cam_regs(scene.cam[L]);
        const uint32_t v[6] = {g.sx, g.sy, g.m00, g.m01, g.m10, g.m11};
        write_array(f, L == L_BG ? "SCN_BG_REGS" : "SCN_FG_REGS", v, 6);
    }
    return fclose(f) == 0;
}

static void save_scenario() {
    if (save_file(file_path)) { unsaved = false; show_status("SAVED %s", file_path.c_str()); }
    else show_status("ERROR: CANNOT WRITE %s", file_path.c_str());
}
static void reload_scenario() {
    Scenario s;
    if (!load_file(file_path, s)) { show_status("ERROR: CANNOT READ %s", file_path.c_str()); return; }
    push_undo();
    scene = s;
    unsaved = false;
    show_status("LOADED %s", file_path.c_str());
}
static void export_scenario() {   // same name, extension .h
    size_t dot = file_path.find_last_of('.'), sl = file_path.find_last_of("/\\");
    bool ext = dot != std::string::npos && (sl == std::string::npos || dot > sl);
    std::string p = file_path.substr(0, ext ? dot : std::string::npos) + ".h";
    if (export_header(p)) show_status("EXPORTED %s", p.c_str());
    else show_status("ERROR: CANNOT WRITE %s", p.c_str());
}

// At startup: the file if it exists, otherwise a new scenario that will be saved there
static void open_scenario() {
    if (load_file(file_path, scene)) {
        show_status("LOADED %s", file_path.c_str());
    } else {
        new_scenario();
        show_status("NEW SCENARIO - CTRL+S SAVES TO %s", file_path.c_str());
    }
}
